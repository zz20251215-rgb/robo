/**
 * One-off generator for the numerical regression fixture.
 * Reads the pre-refactor single-file implementation from .cache/legacy-index.html
 * and records its outputs so the new TypeScript core can be compared against it.
 *
 *   node scripts/gen-reference.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const legacy = readFileSync('.cache/legacy-index.html', 'utf8');
const start = legacy.indexOf('class AnkleModel');
const end = legacy.indexOf('class Canvas2DPad');
if (start < 0 || end < 0) throw new Error('legacy AnkleModel not found');
const source = legacy.slice(start, end);
const AnkleModel = new Function(`${source}\nreturn AnkleModel;`)();

const D2R = Math.PI / 180;
const model = new AnkleModel();

const poses = [
  [0, 0],
  [10, 0],
  [-10, 0],
  [0, 8],
  [12, 6],
  [-12, -6],
  [20, -5],
  [-20, 4],
  [25, 0],
  [-20, 0]
];

const poseRows = poses.map(([pitchDeg, rollDeg]) => {
  const pitch = pitchDeg * D2R;
  const roll = rollDeg * D2R;
  const ik = model.solveIK(pitch, roll);
  if (!ik.success) {
    return { pitchDeg, rollDeg, ikOk: false, singular: null, theta1Deg: null, theta2Deg: null };
  }
  const st = model.getJacobianAndStatics(pitch, roll, ik.theta1, ik.theta2);
  const field = (value) => (st.singular || value === undefined ? null : value);
  return {
    pitchDeg,
    rollDeg,
    ikOk: true,
    singular: !!st.singular,
    theta1Deg: ik.theta1 / D2R,
    theta2Deg: ik.theta2 / D2R,
    mu1Deg: field(st.mu1_deg),
    mu2Deg: field(st.mu2_deg),
    cond: field(st.cond),
    tauM1: field(st.tau_m1),
    tauM2: field(st.tau_m2),
    fRod1: field(st.f_rod1),
    fRod2: field(st.f_rod2)
  };
});

const curve = [];
for (let deg = -30; deg <= 25; deg += 1) {
  const pitch = deg * D2R;
  const ik = model.solveIK(pitch, 0);
  if (!ik.success) {
    curve.push({ pitchDeg: deg, theta1Deg: null, tauM1: null, mu1Deg: null, cond: null });
    continue;
  }
  const st = model.getJacobianAndStatics(pitch, 0, ik.theta1, ik.theta2);
  curve.push({
    pitchDeg: deg,
    theta1Deg: st.singular ? null : ik.theta1 / D2R,
    tauM1: st.singular ? null : st.tau_m1,
    mu1Deg: st.singular ? null : st.mu1_deg,
    cond: st.singular ? 100 : st.cond
  });
}

const fk = poses
  .filter(([pitchDeg, rollDeg]) => model.solveIK(pitchDeg * D2R, rollDeg * D2R).success)
  .map(([pitchDeg, rollDeg]) => {
    const ik = model.solveIK(pitchDeg * D2R, rollDeg * D2R);
    const result = model.solveFK(ik.theta1, ik.theta2, 0, 0);
    return {
      pitchDeg,
      rollDeg,
      fkPitchDeg: (result.pitch * 180) / Math.PI,
      fkRollDeg: (result.roll * 180) / Math.PI
    };
  });

const reference = {
  note: 'Generated by scripts/gen-reference.mjs from .cache/legacy-index.html. Do not edit by hand.',
  neutralThetaDeg: model.solveIK(0, 0).theta1 / D2R,
  poses: poseRows,
  curve,
  fk
};

mkdirSync('tests/fixtures', { recursive: true });
writeFileSync('tests/fixtures/legacy-reference.json', `${JSON.stringify(reference, null, 2)}\n`);
console.log(`wrote tests/fixtures/legacy-reference.json (${poseRows.length} poses, ${curve.length} curve points, ${fk.length} fk rows)`);
